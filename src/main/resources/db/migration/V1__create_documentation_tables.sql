CREATE TABLE scan_execution (
  id VARCHAR(36) PRIMARY KEY,
  repository_key VARCHAR(300) NOT NULL,
  organization VARCHAR(150) NOT NULL,
  project_name VARCHAR(150) NOT NULL,
  repository_name VARCHAR(150) NOT NULL,
  pull_request_id BIGINT,
  scan_scope VARCHAR(20) NOT NULL,
  scope_reason VARCHAR(100) NOT NULL,
  checked_out_ref VARCHAR(255),
  head_commit VARCHAR(64),
  pull_request_resolved BOOLEAN NOT NULL,
  analyzer_version VARCHAR(20) NOT NULL,
  files_scanned INTEGER NOT NULL,
  changed_files INTEGER NOT NULL,
  evidence_added INTEGER NOT NULL,
  evidence_removed INTEGER NOT NULL,
  scanned_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_scan_execution_repository ON scan_execution (repository_key, scanned_at);

CREATE TABLE scan_changed_file (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_id VARCHAR(36) NOT NULL,
  file_path VARCHAR(1000) NOT NULL,
  change_type VARCHAR(20) NOT NULL,
  CONSTRAINT fk_changed_file_scan FOREIGN KEY (scan_id) REFERENCES scan_execution (id)
);

CREATE INDEX ix_scan_changed_file_scan ON scan_changed_file (scan_id);

CREATE TABLE repository_file (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repository_key VARCHAR(300) NOT NULL,
  file_path VARCHAR(1000) NOT NULL,
  blob_sha VARCHAR(64) NOT NULL,
  CONSTRAINT uk_repository_file UNIQUE (repository_key, file_path)
);

CREATE TABLE code_evidence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evidence_id VARCHAR(40) NOT NULL,
  repository_key VARCHAR(300) NOT NULL,
  introduced_scan_id VARCHAR(36) NOT NULL,
  superseded_scan_id VARCHAR(36),
  signal_type VARCHAR(30) NOT NULL,
  source_kind VARCHAR(30),
  language VARCHAR(30),
  technology VARCHAR(50),
  file_path VARCHAR(1000) NOT NULL,
  symbol_name VARCHAR(1000),
  scope_symbol VARCHAR(1000),
  rule_id VARCHAR(100),
  matched_rule VARCHAR(100),
  match_text CLOB,
  severity_hint VARCHAR(20),
  runtime_surface VARCHAR(50),
  dependency_surface VARCHAR(1000),
  probable_cause VARCHAR(1000),
  recovery_action VARCHAR(1000),
  start_line INTEGER NOT NULL,
  end_line INTEGER NOT NULL,
  match_line INTEGER NOT NULL,
  snippet CLOB,
  confidence DOUBLE PRECISION NOT NULL,
  tags VARCHAR(2000)
);

CREATE INDEX ix_code_evidence_current ON code_evidence (repository_key, superseded_scan_id);
CREATE INDEX ix_code_evidence_introduced ON code_evidence (introduced_scan_id);
CREATE INDEX ix_code_evidence_superseded ON code_evidence (superseded_scan_id);

CREATE TABLE document_section_state (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_key VARCHAR(500) NOT NULL,
  section_id VARCHAR(150) NOT NULL,
  title VARCHAR(300) NOT NULL,
  fingerprint VARCHAR(64) NOT NULL,
  body CLOB NOT NULL,
  document_version INTEGER NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT uk_document_section UNIQUE (document_key, section_id)
);

CREATE TABLE document_version (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_key VARCHAR(500) NOT NULL,
  repository_key VARCHAR(300) NOT NULL,
  template_id VARCHAR(150) NOT NULL,
  lifecycle VARCHAR(20) NOT NULL,
  version_number INTEGER NOT NULL,
  document_path VARCHAR(1000) NOT NULL,
  scan_id VARCHAR(36) NOT NULL,
  pull_request_id BIGINT,
  head_commit VARCHAR(64),
  scan_scope VARCHAR(20),
  changed_files INTEGER NOT NULL,
  evidence_added INTEGER NOT NULL,
  evidence_removed INTEGER NOT NULL,
  updated_sections CLOB,
  warnings CLOB,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT uk_document_version UNIQUE (document_key, version_number)
);
